-- OBJETO: TRIGGER trg_validar_stock_detalle
CREATE OR REPLACE TRIGGER trg_validar_stock_detalle
BEFORE INSERT ON detalle_ventas
FOR EACH ROW
DECLARE
  v_stock_disponible NUMBER;
  v_nombre_prod VARCHAR2(100);
BEGIN
  SELECT stock, nombre INTO v_stock_disponible, v_nombre_prod
  FROM productos WHERE producto_id = :NEW.producto_id;
  
  IF v_stock_disponible < :NEW.cantidad THEN
    RAISE_APPLICATION_ERROR(
      -20001,
      'Stock insuficiente para ' || v_nombre_prod || 
      '. Disponible: ' || v_stock_disponible || 
      '. Solicitado: ' || :NEW.cantidad
    );
  END IF;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20002, 'Articulo ID ' || :NEW.producto_id || ' no catalogado.');
END trg_validar_stock_detalle;
/

