-- ESCENARIO 1: FOR UPDATE NOWAIT
DECLARE
  v_stock_actual NUMBER;
  v_nombre_prod VARCHAR2(100);
  v_cantidad NUMBER := 2;
  v_producto_id NUMBER := 1;
  RECURSO_OCUPADO EXCEPTION;
  PRAGMA EXCEPTION_INIT(RECURSO_OCUPADO, -54);
BEGIN
  DBMS_OUTPUT.PUT_LINE('=== ESCENARIO NOWAIT: Iniciando venta de stock ===');
  SELECT nombre, stock INTO v_nombre_prod, v_stock_actual
  FROM productos WHERE producto_id = v_producto_id
  FOR UPDATE NOWAIT;
  
  IF v_stock_actual >= v_cantidad THEN
    UPDATE productos SET stock = stock - v_cantidad WHERE producto_id = v_producto_id;
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('EXITO: Venta autorizada. Stock remanente: ' || (v_stock_actual - v_cantidad));
  ELSE
    ROLLBACK;
    DBMS_OUTPUT.PUT_LINE('RECHAZADO: Stock insuficiente para procesar.');
  END IF;
EXCEPTION
  WHEN RECURSO_OCUPADO THEN
    ROLLBACK;
    DBMS_OUTPUT.PUT_LINE('ALERTA: Fila ocupada por otra sucursal. Reintente en breve para evitar bloqueos infinitos.');
  WHEN OTHERS THEN
    ROLLBACK;
    DBMS_OUTPUT.PUT_LINE('ERROR CRÍTICO SISTEMA: ' || SQLERRM);
END;
/

-- ESCENARIO 2: FOR UPDATE WAIT n
DECLARE
  v_stock NUMBER;
  v_producto_id NUMBER := 1;
  TIMEOUT_EXPIRADO EXCEPTION;
  PRAGMA EXCEPTION_INIT(TIMEOUT_EXPIRADO, -30006);
BEGIN
  DBMS_OUTPUT.PUT_LINE('=== ESCENARIO WAIT 5: Esperando al recurso relacional por 5 segundos ===');
  SELECT stock INTO v_stock FROM productos WHERE producto_id = v_producto_id FOR UPDATE WAIT 5;
  DBMS_OUTPUT.PUT_LINE('Control adquirido tras liberación. Stock actual: ' || v_stock);
  COMMIT;
EXCEPTION
  WHEN TIMEOUT_EXPIRADO THEN
    ROLLBACK;
    DBMS_OUTPUT.PUT_LINE('TIMEOUT: El recurso no fue liberado por la otra sesión tras 5s de cola intelectual.');
  WHEN OTHERS THEN
    ROLLBACK;
    DBMS_OUTPUT.PUT_LINE('ERROR CRÍTICO: ' || SQLERRM);
END;
/


