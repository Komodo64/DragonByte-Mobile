-- OBJETO: STORED PROCEDURE registrar_venta_completa
CREATE OR REPLACE PROCEDURE registrar_venta_completa(
  p_cliente_id IN NUMBER,
  p_producto_id IN NUMBER,
  p_cantidad IN NUMBER
) IS
  v_precio_unit NUMBER(12,2);
  v_stock_actual NUMBER;
  v_nombre_prod VARCHAR2(100);
  v_nueva_venta NUMBER;
BEGIN
  SELECT nombre, precio, stock INTO v_nombre_prod, v_precio_unit, v_stock_actual
  FROM productos WHERE producto_id = p_producto_id;
  
  IF v_stock_actual < p_cantidad THEN
    RAISE_APPLICATION_ERROR(-20010, 'Inventario insuficiente. ' || v_nombre_prod || ' posee ' || v_stock_actual || ' u.');
  END IF;
  
  INSERT INTO ventas (cliente_id, estado) VALUES (p_cliente_id, 'confirmada')
  RETURNING venta_id INTO v_nueva_venta;
  
  INSERT INTO detalle_ventas (venta_id, producto_id, cantidad, precio_unit)
  VALUES (v_nueva_venta, p_producto_id, p_cantidad, v_precio_unit);
  
  UPDATE productos SET stock = stock - p_cantidad WHERE producto_id = p_producto_id;
  UPDATE ventas SET total = p_cantidad * v_precio_unit WHERE venta_id = v_nueva_venta;
  
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('PROCESO EXITOSO: Concretada Venta #' || v_nueva_venta || ' por ' || p_cantidad || ' de ' || v_nombre_prod);
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    ROLLBACK;
    DBMS_OUTPUT.PUT_LINE('FALLIDAS: Cliente o Dispositivo inactivo en el sistema.');
  WHEN OTHERS THEN
    ROLLBACK;
    DBMS_OUTPUT.PUT_LINE('FALLO CRITICO TRANSACCIONAL: Abortado. Motivo: ' || SQLERRM);
END registrar_venta_completa;
/

