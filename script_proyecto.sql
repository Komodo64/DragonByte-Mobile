-- OBJETO: TABLA clientes
CREATE TABLE clientes (
  cliente_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR2(100) NOT NULL,
  email VARCHAR2(120) UNIQUE,
  ciudad VARCHAR2(60)
);

-- OBJETO: TABLA productos
CREATE TABLE productos (
  producto_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR2(100) NOT NULL,
  categoria VARCHAR2(40) NOT NULL,
  stock NUMBER NOT NULL,
  precio NUMBER(12,2) NOT NULL,
  stock_minimo NUMBER DEFAULT 5,
  CONSTRAINT chk_stock_positivo CHECK (stock >= 0),
  CONSTRAINT chk_precio_positivo CHECK (precio > 0)
);

-- OBJETO: TABLA ventas
CREATE TABLE ventas (
  venta_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id NUMBER NOT NULL,
  fecha DATE DEFAULT SYSDATE,
  estado VARCHAR2(20) DEFAULT 'pendiente',
  total NUMBER(14,2) DEFAULT 0,
  CONSTRAINT fk_venta_cliente FOREIGN KEY (cliente_id) REFERENCES clientes(cliente_id),
  CONSTRAINT chk_estado CHECK (estado IN ('pendiente', 'confirmada', 'cancelada'))
);

-- OBJETO: TABLA detalle_ventas
CREATE TABLE detalle_ventas (
  detalle_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venta_id NUMBER NOT NULL,
  producto_id NUMBER NOT NULL,
  cantidad NUMBER NOT NULL,
  precio_unit NUMBER(12,2) NOT NULL,
  CONSTRAINT fk_detalle_venta FOREIGN KEY (venta_id) REFERENCES ventas(venta_id),
  CONSTRAINT fk_detalle_producto FOREIGN KEY (producto_id) REFERENCES productos(producto_id),
  CONSTRAINT chk_cantidad_positiva CHECK (cantidad > 0)
);

-- OBJETO: TABLA log_cambios
CREATE TABLE log_cambios (
  log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tabla_origen VARCHAR2(50),
  campo VARCHAR2(50),
  valor_antes VARCHAR2(200),
  valor_despues VARCHAR2(200),
  operacion VARCHAR2(20),
  fecha DATE DEFAULT SYSDATE
);

