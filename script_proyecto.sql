-- OBJETO: VISTA v_catalogo_publico
CREATE OR REPLACE VIEW v_catalogo_publico AS
SELECT
  producto_id,
  nombre AS producto,
  categoria,
  CASE
    WHEN stock = 0 THEN 'Agotado'
    WHEN stock < 5 THEN 'Pocas unidades'
    ELSE 'Disponible'
  END AS disponibilidad
FROM productos
WHERE stock >= 0;

-- OBJETO: VISTA v_reporte_ventas_detallado
CREATE OR REPLACE VIEW v_reporte_ventas_detallado AS
SELECT
  c.nombre AS cliente,
  c.ciudad,
  p.nombre AS producto,
  p.categoria,
  COUNT(v.venta_id) AS numero_compras,
  SUM(d.cantidad) AS unidades_totales,
  SUM(d.cantidad * d.precio_unit) AS ingreso_generado,
  ROUND(AVG(d.cantidad), 1) AS promedio_por_compra,
  MAX(v.fecha) AS ultima_compra
FROM clientes c
JOIN ventas v ON c.cliente_id = v.cliente_id
JOIN detalle_ventas d ON v.venta_id = d.venta_id
JOIN productos p ON d.producto_id = p.producto_id
WHERE v.estado != 'cancelada'
GROUP BY c.nombre, c.ciudad, p.nombre, p.categoria
ORDER BY ingreso_generado DESC;


